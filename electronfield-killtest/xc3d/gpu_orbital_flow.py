"""Density-directed orbital relaxation coupled to our spin/charge state.

Local charge and spin gates alone left substantial three-electron error. This
new operator family adds real orbital rotations generated by [gamma,Q], using
the trial one-body density gamma. These rotations conserve particle number,
fermionic antisymmetry and total spin and are local in a separated-fragment
density matrix. References are not optimization targets.
"""
from .runtime import configure, torch_setup
ROOT = configure(gpu_only_compatible=True)

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import torch
from .gpu_spin_flow import SpinChargeFlow
from .gpu_sector_flow import optimize, rotate_block


class OrbitalSpinChargeFlow(SpinChargeFlow):
    def __init__(self, data):
        super().__init__(data)
        state = data["sector_block"][0]
        norm = state.square().sum()
        density = (2*torch.einsum("pjk,qjk->pq", state, state)
                   +torch.einsum("ijp,ijq->pq", state, state))/norm
        operator = self.rotation @ torch.diag_embed(self.orbital_spectrum) @ self.rotation.transpose(-1, -2)
        generator = (density @ operator-operator @ density)/4
        self.register_buffer("orbital_generator", (generator-generator.transpose(-1, -2))/2)
        self.orbital_raw = torch.nn.Parameter(torch.zeros_like(self.raw))

    def orbital_update(self, states, layer, mode):
        angle = torch.pi*torch.tanh(self.orbital_raw[layer, mode])
        rotation = torch.matrix_exp(angle*self.orbital_generator[mode])
        return rotate_block(states, rotation)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--steps", type=int, default=400)
    parser.add_argument("--output", type=Path, default=Path("research/orbital_spin_charge_flow_gpu_20261116.json"))
    args = parser.parse_args()
    device = torch_setup()
    report = {"created_utc": datetime.now(timezone.utc).isoformat(), "device": device,
              "scope": "Density-directed orbital, spin and charge correlation operators; three-electron mechanism test, not broad chemical validation",
              "training_targets": "Variational Hamiltonian expectation only; reference energies used for reporting",
              "steps": args.steps, "cases": [], "failures": []}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    for path in sorted((ROOT / "data/gpu_odd_operators").glob("*.flow_seed.pt")):
        try:
            report["cases"].append(optimize(path, args, device, model_class=OrbitalSpinChargeFlow))
        except Exception as exc:
            failure = {"id": path.stem, "exception": f"{type(exc).__name__}: {exc}"}
            report["failures"].append(failure)
            print(json.dumps(failure), flush=True)
        args.output.write_text(json.dumps(report, indent=2)+"\n")
    if report["cases"]:
        errors = torch.tensor([row["error_kcal"] for row in report["cases"]], device=device)
        report["summary"] = {"cases": len(errors), "mae_kcal": float(errors.abs().mean()),
                             "maximum_error_kcal": float(errors.abs().max())}
    report["peak_cuda_bytes"] = torch.cuda.max_memory_allocated()
    args.output.write_text(json.dumps(report, indent=2)+"\n")
    print(json.dumps({"summary": report.get("summary"), "failures": report["failures"]}), flush=True)


if __name__ == "__main__":
    main()
